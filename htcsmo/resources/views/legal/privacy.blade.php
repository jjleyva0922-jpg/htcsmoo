<x-legal-document title="Privacy Policy" icon="shield-check"
    summary="How information is collected, used, protected, shared, and retained within the supply system.">
    <p class="legal-intro">
        This notice explains how the HTC Supply Management System handles information needed to manage user access, requisitions, approvals, inventory operations, notifications, reports, and institutional audit records.
    </p>

    <section class="legal-section">
        <h2><span>1</span>Information collected</h2>
        <ul>
            <li>Identity and account details such as name, school ID, institutional email, username, role, department, and access status.</li>
            <li>Requisition details, requested items, quantities, purposes, remarks, approval decisions, release information, and associated documents.</li>
            <li>Inventory transactions, notifications, personnel changes, and related audit history.</li>
            <li>Security and technical information such as sign-in activity, timestamps, IP address, browser information, and session data.</li>
        </ul>
    </section>

    <section class="legal-section">
        <h2><span>2</span>How information is used</h2>
        <ul>
            <li>Verify accounts and enforce role- and department-based access.</li>
            <li>Route, review, approve, reject, release, and report on requisitions.</li>
            <li>Maintain accurate inventory and operational records.</li>
            <li>Send relevant account, requisition, deadline, and inventory notifications.</li>
            <li>Protect the system, investigate errors or misuse, and support institutional auditing.</li>
        </ul>
    </section>

    <section class="legal-section">
        <h2><span>3</span>Access and disclosure</h2>
        <p>Information is made available according to assigned roles, ownership, department scope, and workflow responsibilities. It may be accessed by authorized College personnel who need it for supply operations, approvals, account administration, reporting, security, or audit purposes. The system is not intended to publish personal information publicly.</p>
    </section>

    <section class="legal-section">
        <h2><span>4</span>Storage and security</h2>
        <p>The system uses access controls, authenticated sessions, password hashing, activity records, and other administrative and technical safeguards. No system can guarantee absolute security, so users must protect their credentials, sign out from shared devices, and promptly report suspected unauthorized access.</p>
    </section>

    <section class="legal-section">
        <h2><span>5</span>Cookies and session data</h2>
        <p>Essential cookies and browser storage may be used to maintain authenticated sessions, protect requests, remember limited interface state, and support notifications. These technologies are used for system operation and security rather than advertising.</p>
    </section>

    <section class="legal-section">
        <h2><span>6</span>Retention</h2>
        <p>Account, requisition, approval, release, inventory, notification, and audit records may be retained for as long as needed for institutional operations, accountability, security, recordkeeping requirements, and applicable policies. Records are not treated as deleted merely because a request is completed or archived.</p>
    </section>

    <section class="legal-section">
        <h2><span>7</span>Your responsibilities and requests</h2>
        <p>Users should keep their profile information accurate and may ask the Supply Management Office or an authorized HTC administrator to review or correct account information. Requests involving official requisition, approval, inventory, or audit records may be subject to institutional recordkeeping requirements.</p>
    </section>

    <section class="legal-section">
        <h2><span>8</span>Updates and contact</h2>
        <p>This notice may be updated when system practices or institutional requirements change. The latest revision date will appear on this page. Privacy questions or concerns should be directed to the Supply Management Office or the College personnel responsible for system and data administration.</p>
    </section>
