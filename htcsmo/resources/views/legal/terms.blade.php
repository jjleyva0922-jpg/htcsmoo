<x-legal-document title="Terms of Service" icon="file-check-2"
    summary="Rules for authorized access to and responsible use of the institutional supply system.">
    <p class="legal-intro">
        These terms govern use of the HTC Supply Management System. By signing in, registering an account, or using the system, you agree to use it only for authorized institutional purposes and in accordance with applicable Holy Trinity College policies.
    </p>

    <section class="legal-section">
        <h2><span>1</span>Authorized use</h2>
        <p>The system is intended for authorized faculty, staff, department heads, administrators, and Supply Management Office personnel. Accounts are personal and may be used only for official requisition, approval, inventory, reporting, and related administrative work.</p>
    </section>

    <section class="legal-section">
        <h2><span>2</span>Account responsibilities</h2>
        <ul>
            <li>Provide accurate institutional identity and department information.</li>
            <li>Keep credentials confidential and use reasonable care when accessing the system.</li>
            <li>Report suspected unauthorized access or incorrect account assignments to the SMO or an authorized system administrator.</li>
            <li>Do not use another person’s account or attempt to obtain access beyond your assigned role.</li>
        </ul>
    </section>

    <section class="legal-section">
        <h2><span>3</span>Requisitions and approvals</h2>
        <p>Submitted requisitions must reflect legitimate institutional needs. Requestors and approvers are responsible for the accuracy of item quantities, purposes, remarks, and decisions entered under their accounts. Electronic approval and activity records may be retained for operational and audit reference.</p>
    </section>

    <section class="legal-section">
        <h2><span>4</span>Prohibited activity</h2>
        <ul>
            <li>Submitting false, misleading, unauthorized, or duplicate requests.</li>
            <li>Attempting to bypass approval routes, permissions, or security controls.</li>
            <li>Altering inventory, personnel, notification, or audit information without authorization.</li>
            <li>Uploading or entering malicious, unlawful, or unrelated content.</li>
            <li>Using system information for non-institutional purposes or disclosing it to unauthorized persons.</li>
        </ul>
    </section>

    <section class="legal-section">
        <h2><span>5</span>Access management</h2>
        <p>Account access may remain pending while identity and department details are verified. Authorized administrators may update roles, departments, or access status according to institutional responsibilities. Access may be suspended when necessary to protect the system, investigate misuse, or reflect changes in institutional assignment.</p>
    </section>

    <section class="legal-section">
        <h2><span>6</span>System availability and records</h2>
        <p>The College may maintain, update, or temporarily restrict the system when operationally necessary. Users should verify critical requisition, release, and inventory information through established office procedures. System records do not replace any additional documentation required by College policy.</p>
    </section>

    <section class="legal-section">
        <h2><span>7</span>Changes and questions</h2>
        <p>These terms may be revised when system functionality or institutional requirements change. The effective and last-updated dates will be shown on this page. Questions should be directed to the Supply Management Office or an authorized HTC system administrator.</p>
    </section>
